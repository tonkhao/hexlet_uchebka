-- Справочник типов партнера + поля, заданные в форме

CREATE TABLE IF NOT EXISTS public.partner_types (
    partner_type_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_type_name varchar(100) NOT NULL UNIQUE
);


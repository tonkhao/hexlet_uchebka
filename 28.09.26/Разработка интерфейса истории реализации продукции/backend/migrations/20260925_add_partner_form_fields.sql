ALTER TABLE public.partners
    ADD COLUMN IF NOT EXISTS partner_type_id smallint
        CONSTRAINT partners_partner_type_id_fkey REFERENCES public.partner_types(partner_type_id),
    ADD COLUMN IF NOT EXISTS legal_address varchar,
    ADD COLUMN IF NOT EXISTS director_name varchar;

CREATE INDEX IF NOT EXISTS idx_partners_partner_type_id
    ON public.partners(partner_type_id);